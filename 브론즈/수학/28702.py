# FizzBuzz 

# i가 3의 배수이면서 5의 배수이면  FizzBuzz
# i가 3의 배수이지만 5의 배수가  아니면 Fizz
# i가 3의 배수가 아니지만 5의 배수이면 Buzz
# i가 3의 배수도 아니고 5의 배수도 아닌 경우 i를 그대로 출력

# FizzBuzz 문제에서 연속으로 출력된 세 개의 문자열이 주어집니다. 이때, 이 세 문자열 다음에 올 문자열은 무엇일까요
# 연속으로 출력된 세 개의 문자열 다음에 올 문자열을 출력하세요. 여러 문자열이 올 수 있는 경우, 아무거나 하나 출력

# 입력
# Fizz
# Buzz
# 11

# 출력
# Fizz (12) -> 3의 배수이지만 5의 배수가 아니기에

# 입력
# 980803
# 980804
# FizzBuzz -> (980805) 3의 배수이면서 5의 배수 이기에

# 출력
# 980806


